def _sha8_of_file(path: Path) -> str:
    """单文件 sha256 前 8 位；读不出来返回 'unreadable'。"""
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()[:8]
    except OSError:
        return "unreadable"


def _sha8_of_dir(path: Path, suffix: str = "") -> str:
    """目录下匹配后缀的所有文件按文件名排序后串起来取 sha8。

    空目录 → 'empty'；读不出来 → 'unreadable'。
    """
    try:
        files = sorted(p for p in path.iterdir() if p.is_file() and p.name.endswith(suffix))
    except OSError:
        return "unreadable"
    if not files:
        return "empty"
    h = hashlib.sha256()
    for f in files:
        h.update(f.name.encode("utf-8"))
        h.update(b"\0")
        try:
            h.update(f.read_bytes())
        except OSError:
            h.update(b"<unreadable>")
        h.update(b"\0")
    return h.hexdigest()[:8]
