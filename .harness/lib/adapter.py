def _render_architecture_table(rules: Dict[str, Any]) -> str:
    layers = (rules.get("architecture") or {}).get("layers") or []
    if not layers:
        return "（rules.yaml 未配置 architecture.layers）"
    lines = ["| 层级 | 路径 | 可导入 |", "|------|------|--------|"]
    for layer in layers:
        name = layer.get("name", "")
        paths = ", ".join(layer.get("paths") or []) or "-"
        can = ", ".join(layer.get("can_import") or []) or "（无）"
        lines.append(f"| {name} | {paths} | {can} |")
    return "\n".join(lines)


def _render_architecture_bullets(rules: Dict[str, Any]) -> str:
    layers = (rules.get("architecture") or {}).get("layers") or []
    if not layers:
        return "- （rules.yaml 未配置 architecture.layers）"
    lines = []
    for layer in layers:
        name = layer.get("name", "")
        paths = ", ".join(layer.get("paths") or []) or "-"
        can = ", ".join(layer.get("can_import") or []) or "无"
        lines.append(f"- **{name}** (`{paths}`) → 可导入: {can}")
    return "\n".join(lines)


def _render_sub_layer_convention(rules: Dict[str, Any]) -> str:
    """渲染 architecture.sub_layer_convention 表格。

    有配置时返回完整的 markdown 小节；无配置时返回空字符串（调用方不渲染整节）。

    规则摘要也写进文档，避免 Agent 误以为只有 paths 前缀匹配，转而错误降低
    治理模式来绕过拦截。
    """
    convention = ((rules.get("architecture") or {}).get("sub_layer_convention") or {})
    if not isinstance(convention, dict) or not convention:
        return ""
    lines = [
        "### 局部子目录归层（sub_layer_convention）",
        "",
        "> **优先级高于 paths 前缀匹配。**"
        " 文件归层时先在路径各部分里查下表目录名（从深到浅），命中即用；"
        "未命中才走 `architecture.layers[].paths` 前缀。",
        "> 示例：`src/frontend/module/**/components/*.tsx` 命中 `components` → 归为"
        " `component` 层，**不**受 `src/frontend/module/` 前缀影响。",
        "",
        "| 目录名 | 归属层 |",
        "|--------|--------|",
    ]
    for dir_name, layer_name in convention.items():
        lines.append(f"| `{dir_name}` | {layer_name} |")
    return "\n".join(lines)


def _render_imports(rules: Dict[str, Any]) -> str:
    imp = rules.get("imports") or {}
    allowed = imp.get("allowed_prefixes") or []
    forbidden = imp.get("forbidden_imports") or []
    parts = []
    if allowed:
        parts.append("**允许前缀**: " + ", ".join(f"`{p}`" for p in allowed))
    if forbidden:
        parts.append("**禁止导入**:")
        for f in forbidden:
            parts.append(f"- `{f}`")
    return "\n".join(parts) if parts else "（rules.yaml 未配置 imports）"


def _render_naming(rules: Dict[str, Any]) -> str:
    naming = rules.get("naming") or {}
    if not naming:
        return "（rules.yaml 未配置 naming）"
    return "\n".join(f"- **{k}**: {v}" for k, v in naming.items())


def _render_project_constraints(rules: Dict[str, Any]) -> str:
    """B8: 渲染 `project_constraints` —— 项目级硬约束(必读)。

    rules.yaml schema::

        project_constraints:
          - title: "不允许 default export"
            why: "Tree-shake 友好;rename refactor 安全。"
            example: "export const Foo = ...; ❌ export default Foo;"
          - "纯字符串也行,直接当一条约束"

    返回值为空字符串 → adapter 不渲染整个章节。
    缺 title 的 dict 项会被静默跳过(generate 时不应该把"(未命名约束)"这种
    bug 视觉糊到 generated/*.md 里;人写漏 title 的概率远大于故意留空)。
    """
    items = (rules or {}).get("project_constraints") or []
    if not isinstance(items, list) or not items:
        return ""
    lines = []
    idx = 0
    for item in items:
        if isinstance(item, str):
            stripped = item.strip()
            if not stripped:
                continue
            idx += 1
            lines.append(f"{idx}. {stripped}")
        elif isinstance(item, dict):
            title = (item.get("title") or "").strip()
            if not title:
                # 缺 title 的 dict 项跳过 —— 见 docstring
                continue
            idx += 1
            lines.append(f"{idx}. **{title}**")
            why = item.get("why")
            if why:
                lines.append(f"   - 为什么: {why}")
            example = item.get("example")
            if example:
                lines.append(f"   - 示例: `{example}`")
    return "\n".join(lines)


def _render_constraints_section(rules: Dict[str, Any]) -> str:
    """渲染 ## 🚨 项目硬约束 章节;无约束时返回空字符串(整段不出现)。

    注:返回值不带尾部空行 —— 由 `_render_shared_body` 的 `"\\n\\n".join` 统一处理
    section 间空行,避免双空行拼接。
    """
    body = _render_project_constraints(rules)
    if not body:
        return ""
    return (
        "## 🚨 项目硬约束(必读)\n\n"
        "> 业务级硬约束,优先于下方架构/导入/命名规范。违反这些约束的代码"
        "应直接拒绝;不写在 lessons 里因为 lesson 是经验、约束是底线。\n\n"
        f"{body}"
    )


def _render_stats(project_context: Dict[str, Any]) -> str:
    summary = project_context.get("summary") or {}
    if not summary:
        return "（尚未运行 scan，或扫描结果缺失）"
    return (
        f"- 文件数: {summary.get('total_files', 0)}\n"
        f"- 组件:   {summary.get('total_components', 0)}\n"
        f"- Hooks:  {summary.get('total_hooks', 0)}\n"
        f"- APIs:   {summary.get('total_apis', 0)}\n"
        f"- 类型:   {summary.get('total_types', 0)}"
    )


def _render_top_items(items: List[Dict[str, Any]], label: str, limit: int = 15) -> str:
    if not items:
        return f"_暂无 {label}_"
    lines = []
    for it in items[:limit]:
        name = it.get("name") or "(unnamed)"
        path = it.get("file_path") or ""
        lines.append(f"- `{name}` — {path}")
    if len(items) > limit:
        lines.append(f"- _… 还有 {len(items) - limit} 个 {label}（详见 project-context.json）_")
    return "\n".join(lines)


def _render_lessons(lessons: List[Dict[str, Any]], limit: int = 20) -> str:
    if not lessons:
        return "_暂无经验记录；可用 `harness lesson add` 添加_"
    parts = []
    for l in lessons[:limit]:
        sev = l.get("severity") or "warning"
        title = l.get("title") or "(untitled)"
        body = (l.get("content") or "").strip()
        # 限制单条 lesson 字数，避免文档膨胀
        if len(body) > 300:
            body = body[:300] + "…"
        applies = ", ".join(l.get("applies_to") or []) or "-"
        parts.append(
            f"### [{sev}] {title}\n\n"
            f"- 适用: `{applies}`\n"
            f"- 关键词: {', '.join(l.get('keywords') or []) or '-'}\n\n"
            f"{body}"
        )
    if len(lessons) > limit:
        parts.append(f"_… 还有 {len(lessons) - limit} 条经验（运行 `harness lesson list`）_")
    return "\n\n".join(parts)


def _render_lessons_brief(lessons: List[Dict[str, Any]], limit: int = 30) -> str:
    """精简版：只输出 title + applies_to + 关键词 + 一行摘要。

    给 Claude / Comate / Ducc 的 generated/*.md 用 —— 系统提示词只承担「索引」职责，
    正文由 PostToolUse hook 的 inject-lessons.sh 按当前文件路径动态注入。
    """
    if not lessons:
        return ("_暂无经验记录；可用 `harness lesson add` 添加。"
                "写代码时若有相关经验会通过 PostToolUse 自动注入。_")

    header = (
        "> 以下仅列标题与适用范围；写代码时相关经验会通过 PostToolUse hook "
        "自动注入完整正文。如需现在查看：`harness lesson show <id>`。\n"
    )
    parts = [header]
    for l in lessons[:limit]:
        sev = l.get("severity") or "warning"
        title = l.get("title") or "(untitled)"
        applies = ", ".join(l.get("applies_to") or []) or "-"
        keywords = ", ".join(l.get("keywords") or []) or "-"
        # 一行摘要：取正文首行（截断到 80 字）
        body = (l.get("content") or "").strip().splitlines()
        first_line = body[0].strip() if body else ""
        if len(first_line) > 80:
            first_line = first_line[:80] + "…"
        lid = l.get("id") or "?"
        line = f"- **[{sev}]** {title} `[{lid}]` — 适用 `{applies}`；关键词 {keywords}"
        if first_line:
            line += f"\n  > {first_line}"
        parts.append(line)
    if len(lessons) > limit:
        parts.append(f"_… 还有 {len(lessons) - limit} 条经验（运行 `harness lesson list`）_")
    return "\n".join(parts)


def _render_new_command_help(rules: Dict[str, Any]) -> str:
    """渲染 `harness new` 用法 —— 给 Agent / 人读版共用。

    动态从 rules 取出已注册的 kinds，避免 README 写死后和 rules 不同步；
    例子里的 default_dir 也按 rules 当前值来，让 `--path` 用法对得上现实。
    """
    kinds_cfg = ((rules or {}).get("templates") or {}).get("kinds") or {}
    if not isinstance(kinds_cfg, dict) or not kinds_cfg:
        # 兜底：rules.yaml 未注册任何 kind 时给固定文案（layer.paths 推断目录）
        kinds_str = "component / page / hook / service / type"
        examples = (
            "- `harness new component UserAvatar`"
            " → `src/components/UserAvatar.tsx`（按 layer.paths 推断）\n"
            "- `harness new component UserAvatar --path src/widgets/`"
            " → `src/widgets/UserAvatar.tsx`（覆盖默认目录）\n"
            "- `harness new hook useTodos --force`"
            " → 同名已存在时也强制建（默认拒绝防覆盖）"
        )
        return _NEW_HELP_TEMPLATE.format(kinds=kinds_str, examples=examples)

    kinds_list = list(kinds_cfg.keys())
    kinds_str = " / ".join(kinds_list)
    # 挑 component（如果有）作为示例 kind，否则用第一个
    sample_kind = "component" if "component" in kinds_cfg else kinds_list[0]
    sample_dir = (kinds_cfg.get(sample_kind) or {}).get("default_dir") or "src/"
    sample_dir = sample_dir.rstrip("/") + "/"
    sample_ext = (kinds_cfg.get(sample_kind) or {}).get("extension") or ".tsx"
    examples = (
        f"- `harness new {sample_kind} UserAvatar`"
        f" → `{sample_dir}UserAvatar{sample_ext}`\n"
        f"- `harness new {sample_kind} UserAvatar --path src/widgets/`"
        f" → `src/widgets/UserAvatar{sample_ext}`（覆盖默认目录）\n"
        f"- `harness new {sample_kind} UserAvatar --force`"
        f" → 同名已存在时也强制建（默认拒绝防覆盖）"
    )
    return _NEW_HELP_TEMPLATE.format(kinds=kinds_str, examples=examples)


_NEW_HELP_TEMPLATE = """```
harness new <kind> <name> [--path <dir>] [--force]
```

- `<kind>`：{kinds}
- `<name>`：文件名（去扩展名），如 `UserAvatar`
- `--path <dir>`：自定义落盘目录，覆盖 `rules.yaml` 默认路径
- `--force`：目标文件已存在或同名冲突时强制创建

**示例**：

{examples}

> 优先级：`--path` > `rules.yaml templates.kinds.<kind>.default_dir` > 算法兜底"""


