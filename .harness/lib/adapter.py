# ---------------------------------------------------------------------------
# 数据载体
# ---------------------------------------------------------------------------


@dataclass
class GenerateContext:
    """生成所需的全部数据。"""

    rules: Dict[str, Any]
    project_context: Dict[str, Any]      # project-context.json；缺失时为 {}
    lessons: List[Dict[str, Any]]         # Lesson 序列化后的 dict，已过滤过期
    version: str
    timestamp: str                        # ISO 8601
    # README adapter 专用：用于头部注释里写「源文件指纹」，让 drift check 不
    # 需要重跑 generate 就能比对是否过期。其它 adapter 不消费这两个字段。
    mode: str = "strict"                  # 当前治理模式（来自 mode-config.json）
    source_hashes: Dict[str, str] = field(default_factory=dict)  # 文件名 → sha8
    # A1 接通点:experience_market.max_lessons 控制 brief 注入条数上限
    max_lessons: int = 10


# ---------------------------------------------------------------------------
# Adapter 基类
# ---------------------------------------------------------------------------


class AgentAdapter(ABC):
    """单个 Agent 的渲染规则。"""

    @property
    @abstractmethod
    def name(self) -> str:
        """文件名（不含扩展名），如 'claude'。"""

    @property
    def display_name(self) -> str:
        """人读名称，用于注释里显示。"""
        return self.name

    @abstractmethod
    def render_body(self, ctx: GenerateContext) -> str:
        """渲染除头部注释外的正文。"""

    # -- 通用入口 -----------------------------------------------------------

    def render(self, ctx: GenerateContext) -> str:
        header = (
            f"<!-- generated by harness {ctx.version} at {ctx.timestamp}"
            f" for {self.display_name}; do not edit, run `harness generate` to refresh -->\n\n"
        )
        return header + self.render_body(ctx).rstrip() + "\n"

    def target_path(self, harness_dir: Path) -> Path:
        return harness_dir / "generated" / f"{self.name}.md"

    # -- 写盘（README adapter 会 override 以保留手写区） ---------------------

    def write_to(self, harness_dir: Path, ctx: GenerateContext) -> Path:
        target = self.target_path(harness_dir)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(self.render(ctx), encoding="utf-8")
        return target


