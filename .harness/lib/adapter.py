def _bash_array(items: List[str]) -> str:
    """把 Python 列表转成 bash 数组字面量,内容做最小转义。"""
    quoted = []
    for it in items:
        # 单引号包,内部单引号转成 '\''
        s = str(it).replace("'", "'\\''")
        quoted.append(f"'{s}'")
    return "( " + " ".join(quoted) + " )" if quoted else "()"


class HooksConfigAdapter(AgentAdapter):
    """生成 `.harness/hooks/.config.sh` —— hook fast-path 用的 bash 变量。

    与三个 markdown adapter 不同:
    - 不进 generated/,直接落 hooks/.config.sh
    - 输出是 bash 而非 markdown
    - 不参与 README source_hashes(它本身就是 rules.yaml 的派生)
    """

    @property
    def name(self) -> str:
        return "hooks-config"

    @property
    def display_name(self) -> str:
        return "Hooks fast-path config"

    def target_path(self, harness_dir: Path) -> Path:
        return harness_dir / "hooks" / ".config.sh"

    def render_body(self, ctx: GenerateContext) -> str:
        scanner = (ctx.rules or {}).get("scanner") or {}
        source_root = scanner.get("source_root") or "src"
        if isinstance(source_root, str) and source_root.rstrip("/") == ".":
            source_root = ""
        include_ext = scanner.get("include_extensions") or [".ts", ".tsx", ".d.ts", ".js", ".jsx"]
        exclude_dirs = scanner.get("exclude_dirs") or []
        # exclude_globs 不再输出:复杂 glob 交给 `harness should-validate` CLI 兜底,
        # bash glob (case 模式) 与 Python fnmatch 语义不完全一致(尤其 `**`),
        # 维护两套引擎容易引 bug,不如 fork 一次 CLI 干净。

        market = (ctx.rules or {}).get("experience_market") or {}
        market_enabled = 1 if market.get("enabled", True) else 0

        return (
            f"# Auto-generated by harness {ctx.version} at {ctx.timestamp}\n"
            f"# DO NOT EDIT — run `harness generate` to refresh.\n"
            f"# Sourced by .harness/hooks/*.sh for fast-path filtering before\n"
            f"# invoking the Python CLI. Run `harness doctor` if generated config looks stale.\n"
            f"\n"
            f"HARNESS_SOURCE_ROOT={_bash_quote(source_root)}\n"
            f"HARNESS_INCLUDE_EXT={_bash_array(list(include_ext))}\n"
            f"HARNESS_EXCLUDE_DIRS={_bash_array(list(exclude_dirs))}\n"
            f"HARNESS_MODE={_bash_quote(ctx.mode)}\n"
            f"HARNESS_EXPERIENCE_ENABLED={market_enabled}\n"
        )

    def render(self, ctx: GenerateContext) -> str:
        # 覆盖基类:bash 文件不带 markdown 注释头,直接用 render_body
        return self.render_body(ctx)


def _bash_quote(value: str) -> str:
    s = str(value).replace("'", "'\\''")
    return f"'{s}'"


class Generator:
    """统一调度 adapter 的渲染与落盘。"""

    DEFAULT_ADAPTERS = (ClaudeAdapter, ComateAdapter, DuccAdapter, ReadmeAdapter, HooksConfigAdapter)

    # 哪些文件参与 README 的 source hash —— 改这里等于改 drift check 的口径
    SOURCE_FILES = ("rules.yaml", "mode-config.json")
    LESSONS_DIR = ("memory", "lessons")

    def __init__(
        self,
        harness_dir: Path,
        version: str = "0.0.0",
        adapters: Optional[List[AgentAdapter]] = None,
    ) -> None:
        self.harness_dir = Path(harness_dir).resolve()
        self.version = version
        self.adapters: List[AgentAdapter] = (
            adapters if adapters is not None else [cls() for cls in self.DEFAULT_ADAPTERS]
        )

    # -- 公共 API -----------------------------------------------------------

    def generate_all(self) -> GenerateResult:
        ctx = self._build_context()
        result = GenerateResult()

        for adapter in self.adapters:
            target = adapter.write_to(self.harness_dir, ctx)
            try:
                rel = str(target.relative_to(self.harness_dir.parent))
            except ValueError:
                rel = str(target)
            result.written.append(rel)
        return result

    # -- 内部：数据装载 ------------------------------------------------------

    def _build_context(self) -> GenerateContext:
        rules = self._load_rules()
        project_context = self._load_project_context()
        lessons = self._load_lessons(rules=rules)
        market_cfg = (rules or {}).get("experience_market") or {}
        max_lessons = market_cfg.get("max_lessons", 10)
        if not isinstance(max_lessons, int) or max_lessons <= 0:
            max_lessons = 10
        return GenerateContext(
            rules=rules,
            project_context=project_context,
            lessons=lessons,
            version=self.version,
            timestamp=_dt.datetime.now().isoformat(timespec="seconds"),
            mode=self._load_mode(),
            source_hashes=self._compute_source_hashes(),
            max_lessons=max_lessons,
        )

    def _load_rules(self) -> Dict[str, Any]:
        rules_file = self.harness_dir / "rules.yaml"
        if not rules_file.exists():
            return {}
        try:
            import yaml
            return yaml.safe_load(rules_file.read_text(encoding="utf-8")) or {}
        except Exception:
            return {}

    def _load_project_context(self) -> Dict[str, Any]:
        ctx_file = self.harness_dir / "context" / "project-context.json"
        if not ctx_file.exists():
            return {}
        try:
            return json.loads(ctx_file.read_text(encoding="utf-8")) or {}
        except (json.JSONDecodeError, OSError):
            return {}

    def _load_mode(self) -> str:
        """从 mode-config.json 读当前模式；缺失/损坏返回默认 strict。"""
        mode_file = self.harness_dir / "mode-config.json"
        if not mode_file.exists():
            return "strict"
        try:
            data = json.loads(mode_file.read_text(encoding="utf-8")) or {}
            mode = data.get("mode")
            return mode if isinstance(mode, str) and mode else "strict"
        except (json.JSONDecodeError, OSError):
            return "strict"

    def _compute_source_hashes(self) -> Dict[str, str]:
        """计算 README 关心的源文件指纹。

        - rules.yaml / mode-config.json：单文件取 sha256 前 8 位，缺失记 'missing'
        - lessons：把 lessons/ 下所有 *.md 的内容串起来取一次 sha8（顺序固定，
          与文件名排序一致），目录不存在记 'missing'
        """
        out: Dict[str, str] = {}
        for fname in self.SOURCE_FILES:
            f = self.harness_dir / fname
            out[fname] = _sha8_of_file(f) if f.exists() else "missing"

        lessons_dir = self.harness_dir.joinpath(*self.LESSONS_DIR)
        out["lessons"] = _sha8_of_dir(lessons_dir, suffix=".md") if lessons_dir.exists() else "missing"
        return out

    def _load_lessons(self, rules: Optional[Dict[str, Any]] = None) -> List[Dict[str, Any]]:
        """从 ExperienceMarket 拉所有未过期 lesson，按 created_at 倒序。

        rules 提供时 experience_market.enabled=false 直接返回空列表(A1 接通点)。
        """
        market_cfg = ((rules or {}).get("experience_market") or {})
        if market_cfg.get("enabled", True) is False:
            return []
        # 延迟 import：避免 adapter 单测必须依赖经验市场
        from lib.experience_market import ExperienceMarket
        from dataclasses import asdict

        market = ExperienceMarket(harness_dir=self.harness_dir)
        all_lessons = market.list_lessons()

        now = _dt.datetime.now()
        active = []
        for l in all_lessons:
            if l.expires_at:
                try:
                    if _dt.datetime.fromisoformat(l.expires_at) < now:
                        continue
                except ValueError:
                    pass  # 解析失败 → 当作未过期保留
            active.append(asdict(l))

        active.sort(key=lambda d: d.get("created_at") or "", reverse=True)
        return active


