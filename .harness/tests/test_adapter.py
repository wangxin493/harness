RULES_YAML = textwrap.dedent("""\
architecture:
  layers:
    - name: component
      paths: ["src/components/", "src/pages/"]
      can_import: ["hook", "service", "type"]
    - name: hook
      paths: ["src/hooks/"]
      can_import: ["service", "type"]
    - name: service
      paths: ["src/api/"]
      can_import: ["type"]
imports:
  allowed_prefixes: ["@/types", "@/api", "@/components"]
  forbidden_imports: ["@/services", "@/api/mockApi"]
naming:
  component: PascalCase
  hook: camelCase-with-use-prefix
""")


PROJECT_CONTEXT = {
    "summary": {
        "total_files": 10,
        "total_components": 4,
        "total_hooks": 2,
        "total_apis": 3,
        "total_types": 1,
    },
    "components": [
        {"name": "Btn", "file_path": "src/components/Btn.tsx"},
        {"name": "Header", "file_path": "src/components/Header.tsx"},
    ],
    "hooks": [{"name": "useFoo", "file_path": "src/hooks/useFoo.ts"}],
    "apis": [{"name": "itemService", "file_path": "src/api/itemService.ts"}],
    "types": [{"name": "Item", "file_path": "src/types/item.ts"}],
}


def _make_ctx(rules=None, project_context=None, lessons=None):
    return GenerateContext(
        rules=rules if rules is not None else {},
        project_context=project_context if project_context is not None else {},
        lessons=lessons or [],
        version="2.0.0-test",
        timestamp="2026-06-17T20:00:00",
    )


