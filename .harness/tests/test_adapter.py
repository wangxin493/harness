# 单 adapter 渲染
# ---------------------------------------------------------------------------


class TestAdapterRender(unittest.TestCase):
    def setUp(self):
        import yaml
        self.rules = yaml.safe_load(RULES_YAML)
        self.ctx = _make_ctx(
            rules=self.rules,
            project_context=PROJECT_CONTEXT,
            lessons=[
                {
                    "id": "L1", "title": "禁止 @/services",
                    "category": "import", "severity": "error",
                    "keywords": ["forbidden"], "applies_to": ["src/api/"],
                    "content": "已迁移到 @/api。", "author": "alice",
                    "created_at": "2026-06-01T10:00:00", "expires_at": None,
                }
            ],
        )

    def test_header_contains_version_and_timestamp(self):
        out = ClaudeAdapter().render(self.ctx)
        self.assertIn("generated by harness 2.0.0-test", out)
        self.assertIn("2026-06-17T20:00:00", out)
        self.assertTrue(out.startswith("<!--"))

    def test_claude_renders_architecture_table_and_imports(self):
        out = ClaudeAdapter().render(self.ctx)
        # 表格表头
        self.assertIn("| 层级 | 路径 | 可导入 |", out)
        # layers 内容
        self.assertIn("component", out)
        self.assertIn("src/components/", out)
        # 禁止导入
        self.assertIn("@/services", out)
        self.assertIn("@/api/mockApi", out)
        # 项目状态
        self.assertIn("文件数: 10", out)
        self.assertIn("组件:   4", out)
        # 经验注入
        self.assertIn("禁止 @/services", out)
        self.assertIn("已迁移到 @/api", out)

    def test_comate_inlines_everything_no_at_refs(self):
        out = ComateAdapter().render(self.ctx)
        # 不能出现 Claude 的 @ 引用风格
        self.assertNotIn("@/.harness/rules.yaml", out)
        self.assertNotIn("@.harness/generated/", out)
        # 但仍带规则正文
        self.assertIn("禁止导入", out)
        self.assertIn("@/services", out)
        # 类型/API 列表
        self.assertIn("Item", out)
        self.assertIn("itemService", out)

    def test_ducc_uses_bullets_for_layers(self):
        out = DuccAdapter().render(self.ctx)
        # bullet 风格
        self.assertIn("- **component**", out)
        self.assertIn("- **hook**", out)
        # 同样有经验
        self.assertIn("禁止 @/services", out)

    def test_target_path(self):
        from pathlib import Path as P
        harness = P("/tmp/x/.harness")
        self.assertEqual(
            ClaudeAdapter().target_path(harness),
            harness / "generated" / "claude.md",
        )
        self.assertEqual(
            ComateAdapter().target_path(harness),
            harness / "generated" / "comate.md",
        )
        self.assertEqual(
            DuccAdapter().target_path(harness),
            harness / "generated" / "ducc.md",
        )


