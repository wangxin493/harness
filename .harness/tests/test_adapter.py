class TestAdapterRender(unittest.TestCase):
    def setUp(self):
        import yaml
        self.rules = yaml.safe_load(RULES_YAML)
        self.ctx = _make_ctx(
            rules=self.rules,
            project_context=PROJECT_CONTEXT,
            lessons=[
                {
                    "id": "L1", "title": "禁止 @/services",
                    "category": "import", "severity": "error",
                    "keywords": ["forbidden"], "applies_to": ["src/api/"],
                    "content": "已迁移到 @/api。", "author": "alice",
                    "created_at": "2026-06-01T10:00:00", "expires_at": None,
                }
            ],
        )

    def test_header_contains_version_and_timestamp(self):
        out = ClaudeAdapter().render(self.ctx)
        self.assertIn("generated by harness 2.0.0-test", out)
        self.assertIn("2026-06-17T20:00:00", out)
        self.assertTrue(out.startswith("<!--"))

    def test_claude_renders_architecture_table_and_imports(self):
        out = ClaudeAdapter().render(self.ctx)
        # 表格表头
        self.assertIn("| 层级 | 路径 | 可导入 |", out)
        # layers 内容
        self.assertIn("component", out)
        self.assertIn("src/components/", out)
        # 禁止导入
        self.assertIn("@/services", out)
        self.assertIn("@/api/mockApi", out)
        # 项目状态
        self.assertIn("文件数: 10", out)
        self.assertIn("组件:   4", out)
        # 经验注入
        self.assertIn("禁止 @/services", out)
        self.assertIn("已迁移到 @/api", out)

    def test_comate_inlines_everything_no_at_refs(self):
        out = ComateAdapter().render(self.ctx)
        # 不能出现 Claude 的 @ 引用风格
        self.assertNotIn("@/.harness/rules.yaml", out)
        self.assertNotIn("@.harness/generated/", out)
        # 但仍带规则正文
        self.assertIn("禁止导入", out)
        self.assertIn("@/services", out)
        # 类型/API 列表
        self.assertIn("Item", out)
        self.assertIn("itemService", out)

    def test_ducc_uses_bullets_for_layers(self):
        out = DuccAdapter().render(self.ctx)
        # bullet 风格
        self.assertIn("- **component**", out)
        self.assertIn("- **hook**", out)
        # 同样有经验
        self.assertIn("禁止 @/services", out)

    def test_target_path(self):
        from pathlib import Path as P
        harness = P("/tmp/x/.harness")
        self.assertEqual(
            ClaudeAdapter().target_path(harness),
            harness / "generated" / "claude.md",
        )
        self.assertEqual(
            ComateAdapter().target_path(harness),
            harness / "generated" / "comate.md",
        )
        self.assertEqual(
            DuccAdapter().target_path(harness),
            harness / "generated" / "ducc.md",
        )

    def test_claude_renders_harness_new_help(self):
        """B3: generated/claude.md 必须包含 harness new --path 用法说明。"""
        out = ClaudeAdapter().render(self.ctx)
        # 标题节
        self.assertIn("## 🆕 新建文件", out)
        # 命令签名
        self.assertIn("harness new <kind> <name>", out)
        # --path / --force 都要写出来
        self.assertIn("--path", out)
        self.assertIn("--force", out)
        # 至少一个 --path 例子
        self.assertIn("--path src/widgets/", out)
        # 优先级说明
        self.assertIn("优先级", out)

    def test_ducc_renders_harness_new_help(self):
        """Ducc adapter 同样要带 harness new 用法。"""
        out = DuccAdapter().render(self.ctx)
        self.assertIn("## 🆕 新建文件", out)
        self.assertIn("--path", out)

    def test_new_help_uses_rules_default_dir(self):
        """例子里的 default_dir 应跟 rules.yaml 当前值（不写死 src/components/）。"""
        # 改 rules：把 component 默认目录设成 src/widgets/
        rules = dict(self.rules)
        rules["templates"] = {
            "kinds": {
                "component": {
                    "default_dir": "src/widgets/",
                    "extension": ".tsx",
                },
            },
        }
        ctx = _make_ctx(rules=rules, project_context=PROJECT_CONTEXT, lessons=[])
        out = ClaudeAdapter().render(ctx)
        # 例子中的默认路径应反映 rules.yaml 改动
        self.assertIn("src/widgets/UserAvatar.tsx", out)

    def test_adapters_render_sub_layer_convention(self):
        """Agent 文档必须展示局部子目录归层，避免误判 paths 前缀。"""
        for adapter in (ClaudeAdapter(), ComateAdapter(), DuccAdapter()):
            out = adapter.render(self.ctx)
            self.assertIn("局部子目录归层", out)
            self.assertIn("优先级高于 paths 前缀匹配", out)
            self.assertIn("| `components` | component |", out)
            self.assertIn("| `hooks` | hook |", out)
            self.assertIn("| `utils` | util |", out)

    def test_claude_warns_not_to_downgrade_mode_to_bypass_validation(self):
        out = ClaudeAdapter().render(self.ctx)
        self.assertIn("不要为了绕过验证自行执行 `harness mode relaxed/off`", out)


