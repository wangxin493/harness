class GeneratorFixture:
    def __init__(self):
        self.root = Path(tempfile.mkdtemp(prefix="harness-gen-")).resolve()
        self.harness_dir = self.root / ".harness"
        self.harness_dir.mkdir()

    def write_rules(self, content: str = RULES_YAML):
        (self.harness_dir / "rules.yaml").write_text(content, encoding="utf-8")

    def write_project_context(self, data=PROJECT_CONTEXT):
        ctx_dir = self.harness_dir / "context"
        ctx_dir.mkdir(parents=True, exist_ok=True)
        (ctx_dir / "project-context.json").write_text(
            json.dumps(data, ensure_ascii=False), encoding="utf-8")

    def write_lesson(self, lesson_id: str, **frontmatter):
        from lib.experience_market import ExperienceMarket
        m = ExperienceMarket(harness_dir=self.harness_dir)
        m.add_lesson(
            title=frontmatter.get("title", "t"),
            content=frontmatter.get("content", "body"),
            category=frontmatter.get("category", "general"),
            severity=frontmatter.get("severity", "warning"),
            keywords=frontmatter.get("keywords", []),
            applies_to=frontmatter.get("applies_to", []),
            lesson_id=lesson_id,
            expires_at=frontmatter.get("expires_at"),
        )

    def gen(self) -> Generator:
        return Generator(harness_dir=self.harness_dir, version="2.0.0-test")

    def cleanup(self):
        shutil.rmtree(self.root, ignore_errors=True)


class TestGenerator(unittest.TestCase):
    def setUp(self):
        self.fx = GeneratorFixture()

    def tearDown(self):
        self.fx.cleanup()

    def test_generate_writes_three_files(self):
        self.fx.write_rules()
        self.fx.write_project_context()
        result = self.fx.gen().generate_all()

        self.assertEqual(len(result.written), 3)
        out_dir = self.fx.harness_dir / "generated"
        self.assertTrue((out_dir / "claude.md").exists())
        self.assertTrue((out_dir / "comate.md").exists())
        self.assertTrue((out_dir / "ducc.md").exists())

        # claude.md 包含从 rules.yaml 来的实际内容
        text = (out_dir / "claude.md").read_text(encoding="utf-8")
        self.assertIn("@/services", text)
        self.assertIn("文件数: 10", text)

    def test_generate_loads_lessons_and_skips_expired(self):
        self.fx.write_rules()
        self.fx.write_project_context()
        self.fx.write_lesson("active", title="有效",
                             content="active body",
                             keywords=["k"])
        self.fx.write_lesson("expired", title="过期",
                             content="expired body",
                             expires_at="2020-01-01T00:00:00")
        self.fx.gen().generate_all()

        text = (self.fx.harness_dir / "generated" / "claude.md").read_text(
            encoding="utf-8")
        self.assertIn("有效", text)
        self.assertIn("active body", text)
        self.assertNotIn("过期", text)
        self.assertNotIn("expired body", text)

    def test_generate_works_without_scan(self):
        # 没有 project-context.json 也不应崩
        self.fx.write_rules()
        result = self.fx.gen().generate_all()
        self.assertEqual(len(result.written), 3)
        text = (self.fx.harness_dir / "generated" / "claude.md").read_text(
            encoding="utf-8")
        self.assertIn("尚未运行 scan", text)
        # 但架构规则仍然完整
        self.assertIn("component", text)

    def test_generate_works_without_rules(self):
        # 连 rules.yaml 都没有也不应崩（只是内容降级）
        result = self.fx.gen().generate_all()
        self.assertEqual(len(result.written), 3)
        text = (self.fx.harness_dir / "generated" / "claude.md").read_text(
            encoding="utf-8")
        self.assertIn("rules.yaml 未配置 architecture.layers", text)

    def test_overwrites_existing(self):
        self.fx.write_rules()
        out_dir = self.fx.harness_dir / "generated"
        out_dir.mkdir(parents=True, exist_ok=True)
        (out_dir / "claude.md").write_text("STALE", encoding="utf-8")

        self.fx.gen().generate_all()
        text = (out_dir / "claude.md").read_text(encoding="utf-8")
        self.assertNotIn("STALE", text)
        self.assertIn("项目规范", text)

    def test_relative_path_in_result(self):
        self.fx.write_rules()
        result = self.fx.gen().generate_all()
        # 路径相对 project_dir，便于 CLI 打印
        for p in result.written:
            self.assertTrue(p.startswith(".harness/generated/"))


if __name__ == "__main__":
    unittest.main()
