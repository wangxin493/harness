class TestReadmeAdapter(unittest.TestCase):
    def setUp(self):
        self.fx = GeneratorFixture()
        self.fx.write_rules()
        self.fx.write_project_context()

    def tearDown(self):
        self.fx.cleanup()

    def _readme(self) -> Path:
        return self.fx.harness_dir / "README.md"

    def test_first_run_writes_default_handwritten_block(self):
        self.fx.gen().generate_all()
        text = self._readme().read_text(encoding="utf-8")

        # 顶部 marker
        self.assertIn("AUTOGENERATED by harness 2.0.0-test", text)
        self.assertIn("<!-- sources:", text)
        # 自动区/手写区两块都在
        self.assertIn(README_AUTO_BEGIN, text)
        self.assertIn(README_AUTO_END, text)
        self.assertIn(README_HANDWRITTEN_BEGIN, text)
        self.assertIn(README_HANDWRITTEN_END, text)
        # 自动区有规则内容
        self.assertIn("@/services", text)
        self.assertIn("strict", text)  # mode
        # 手写区有默认模板示例
        self.assertIn("背景与原则", text)

    def test_second_run_preserves_handwritten_edits(self):
        self.fx.gen().generate_all()
        original = self._readme().read_text(encoding="utf-8")

        # 模拟用户手改了手写区
        edited = original.replace(
            "## 背景与原则（手写区）",
            "## 背景与原则（手写区）\n\n这是我自己写的内容 ABCD123",
        )
        self._readme().write_text(edited, encoding="utf-8")

        # 再生成一次：手写区必须保留，自动区刷新
        self.fx.gen().generate_all()
        after = self._readme().read_text(encoding="utf-8")
        self.assertIn("ABCD123", after, "手写区被覆盖了")
        # 自动区仍然在（且包含规则）
        self.assertIn("@/services", after)

    def test_second_run_overwrites_autogenerated_block(self):
        self.fx.gen().generate_all()
        original = self._readme().read_text(encoding="utf-8")

        # 模拟有人手改了自动区里的内容（只动自动区，避免污染手写区）
        auto = ReadmeAdapter.extract_auto_block(original)
        self.assertIsNotNone(auto)
        tampered = original.replace(
            auto, auto.replace("@/services", "@/SOMETHING_BROKEN"))
        self._readme().write_text(tampered, encoding="utf-8")

        # 再生成：自动区会被覆盖回正
        self.fx.gen().generate_all()
        after_auto = ReadmeAdapter.extract_auto_block(
            self._readme().read_text(encoding="utf-8"))
        self.assertIn("@/services", after_auto)
        self.assertNotIn("@/SOMETHING_BROKEN", after_auto)

    def test_source_hashes_change_when_rules_change(self):
        self.fx.gen().generate_all()
        first = ReadmeAdapter.extract_source_hashes(
            self._readme().read_text(encoding="utf-8"))
        self.assertIn("rules.yaml", first)
        self.assertIn("lessons", first)
        self.assertIn("mode-config.json", first)

        # 改 rules.yaml，重生成；rules.yaml 的 sha 应当变
        (self.fx.harness_dir / "rules.yaml").write_text(
            RULES_YAML + "\n# tweak\n", encoding="utf-8")
        self.fx.gen().generate_all()
        second = ReadmeAdapter.extract_source_hashes(
            self._readme().read_text(encoding="utf-8"))
        self.assertNotEqual(first["rules.yaml"], second["rules.yaml"])
        # lessons 没动，应该不变
        self.assertEqual(first["lessons"], second["lessons"])

    def test_extract_handwritten_returns_none_for_missing_markers(self):
        self.assertIsNone(ReadmeAdapter._extract_handwritten(""))
        self.assertIsNone(ReadmeAdapter._extract_handwritten("just text"))

    def test_onboarding_block_at_top(self):
        """B7: 接入说明应位于 README 头部、AUTOGENERATED 之前。"""
        self.fx.gen().generate_all()
        text = self._readme().read_text(encoding="utf-8")
        # 接入说明出现位置在 AUTOGENERATED START 之前
        idx_onboarding = text.find("在新项目中接入 harness")
        idx_auto_begin = text.find(README_AUTO_BEGIN)
        self.assertGreater(idx_onboarding, 0, "接入说明应该在文档里")
        self.assertGreater(idx_auto_begin, idx_onboarding,
                           "接入说明应在 AUTOGENERATED 之前")

    def test_onboarding_block_mentions_setup(self):
        """接入说明应推荐 harness setup 命令。"""
        self.fx.gen().generate_all()
        text = self._readme().read_text(encoding="utf-8")
        self.assertIn("harness setup", text)
        self.assertIn("--agent claude", text)

    def test_onboarding_block_has_old_project_section(self):
        """接入说明里要有"老项目接入"务实派子节,讲只管增量不管存量。"""
        self.fx.gen().generate_all()
        text = self._readme().read_text(encoding="utf-8")
        self.assertIn("老项目接入", text)
        # "只管增量"或"不管存量"是核心论断
