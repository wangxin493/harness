class TestAdapterEdgeCases(unittest.TestCase):
    def test_no_rules_no_scan_no_lessons(self):
        ctx = _make_ctx()
        for adapter in (ClaudeAdapter(), ComateAdapter(), DuccAdapter()):
            out = adapter.render(ctx)
            self.assertIn("rules.yaml 未配置 architecture.layers", out)
            self.assertIn("尚未运行 scan", out)
            self.assertIn("暂无经验记录", out)

    def test_long_lesson_is_truncated(self):
        long_body = "x" * 600
        ctx = _make_ctx(
            lessons=[{
                "id": "L", "title": "超长", "category": "general",
                "severity": "warning", "keywords": [], "applies_to": [],
                "content": long_body, "author": "a",
                "created_at": "2026-06-01T00:00:00", "expires_at": None,
            }],
        )
        out = ClaudeAdapter().render(ctx)
        # 截断到 300 字符 + 省略号
        self.assertIn("…", out)
        self.assertNotIn("x" * 400, out)


